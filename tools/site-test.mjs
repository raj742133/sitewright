section = 'accessibility (axe)';
for (const p of ['/', '/components/', '/components/area-chart/', '/dashboards/', '/icons/'])
  for (const [label, vp, scheme] of [['light desktop', 'wide', 'light'], ['dark desktop', 'wide', 'dark'], ['light phone', 'phone', 'light'], ['dark phone', 'phone', 'dark']]) {
    const { ctx, page } = await openAt(vp, p, { colorScheme: scheme }); await page.waitForTimeout(1200);
    await page.addScriptTag({ content: AXE });
    const res = await page.evaluate(async () => { const r = await window.axe.run(document, { resultTypes: ['violations'], exclude: [['iframe']] }); return r.violations.map((v) => ({ id: v.id, impact: v.impact, help: v.help, n: v.nodes.length, sample: v.nodes.slice(0, 3).map((x) => x.target.join(' ')) })); });
    await check(`${p} ${label}: no serious or critical accessibility violations`, async () => {
      const bad = res.filter((v) => v.impact === 'serious' || v.impact === 'critical'); eq(bad.map((v) => `${v.id} x${v.n} [${v.sample.join(' ; ')}]`).join('  ||  '), '', 'violations');
    });
    for (const v of res.filter((x) => x.impact === 'moderate' || x.impact === 'minor')) warn(`${p} ${label}: ${v.id} (${v.impact}) x${v.n}: ${v.help}`);
    await ctx.close();
  }

