for (const p of ['/', '/components/', '/components/area-chart/', '/dashboards/', '/icons/']) {
  const { ctx, page } = await openAt('wide', p);
  await check(`${p}: header has the nav, search and theme controls; each nav link reaches its page; skip link and landmarks`, async () => {
    const links = await page.$$eval('header nav a', (a) => a.map((x) => [x.textContent.trim(), x.getAttribute('href')])); eq(links.map((l) => l[0]).join('|'), 'Components|Dashboards|Effects|Icons|Docs|GitHub', 'nav items');
    for (const [, h] of links.filter((l) => l[1].startsWith('/'))) eq((await get(abs(h))).status, 200, h);
    truthy(await page.locator('#search').isVisible() && await page.locator('#theme').isVisible(), 'search and theme');
    eq(await page.locator('main').count(), 1, 'main'); eq(await page.locator('header.top').count(), 1, 'header'); eq(await page.locator('footer').count(), 1, 'footer');
    await page.keyboard.press('Tab'); eq(await page.evaluate(() => document.activeElement.className), 'skip', 'first tab stop is the skip link');
  });
  await ctx.close();
}
{
  const { ctx, page } = await openAt('wide', '/components/', { colorScheme: 'light' });
  await check('the theme toggle switches light and dark, is remembered across pages and reloads, and previews follow', async () => {
    await page.click('#theme'); eq(await page.evaluate(() => document.documentElement.dataset.theme), 'dark', 'dark'); await page.waitForTimeout(1200);
    eq(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(12, 12, 11)', 'dark surface');
    const fr = page.frames().find((f) => f.url().includes('/demo/effects/c/')); if (fr) eq(await fr.evaluate(() => document.documentElement.dataset.theme), 'dark', 'preview theme');
    await page.goto(abs('/components/area-chart/')); eq(await page.evaluate(() => document.documentElement.dataset.theme), 'dark', 'persisted'); eq(await page.getAttribute('#stage', 'data-theme'), 'dark', 'stage follows');
    await page.click('#theme'); eq(await page.evaluate(() => document.documentElement.dataset.theme), 'light', 'light again');
  });
  await ctx.close();
  const d = await openAt('wide', '/components/', { colorScheme: 'dark' });
  await check('with no saved choice the pages follow the device (dark)', async () => eq(await d.page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(12, 12, 11)', 'surface'));
  await d.ctx.close();
}

